/**
 * السكانر بيكتب كأنه كيبورد. لو لغة الجهاز عربي، الحروف اللي السكانر "ضغطها"
 * بتطلع عربي (S → ٍ ، T → لإ ، U → ‘ ...). الدالة دي بترجّع كل حرف للزرار
 * الإنجليزي اللي اتضغط فعلاً — بالـ Shift ومن غيره.
 *
 * ⚠️ النسخة القديمة كانت ناقصة حروف كتير مع Shift (أهمها U → ‘)، فكود زي STU-00012
 * كان بيوصل "ST‘-00012" والسكان يفشل. الباك إند كمان بيعمل نفس التصليح كخط دفاع تاني
 * (shared/utils/student-code.util.ts) — أي تعديل هنا يتعمل هناك.
 */

// من غير Shift
const AR_PLAIN: Record<string, string> = {
  'ض': 'q', 'ص': 'w', 'ث': 'e', 'ق': 'r', 'ف': 't', 'غ': 'y', 'ع': 'u', 'ه': 'i', 'خ': 'o', 'ح': 'p', 'ج': '[', 'د': ']',
  'ش': 'a', 'س': 's', 'ي': 'd', 'ب': 'f', 'ل': 'g', 'ا': 'h', 'ت': 'j', 'ن': 'k', 'م': 'l', 'ك': ';', 'ط': "'",
  'ئ': 'z', 'ء': 'x', 'ؤ': 'c', 'ر': 'v', 'ى': 'n', 'ة': 'm', 'و': ',', 'ز': '.', 'ظ': '/', 'ذ': '`',
};

// مع Shift (السكانر بيضغط Shift للحروف الكابيتال)
const AR_SHIFT: Record<string, string> = {
  'َ': 'Q', 'ً': 'W', 'ُ': 'E', 'ٌ': 'R', 'إ': 'Y', '‘': 'U', '÷': 'I', '×': 'O', '؛': 'P',
  'ِ': 'A', 'ٍ': 'S', ']': 'D', '[': 'F', 'أ': 'H', 'ـ': 'J', '،': 'K', '/': 'L',
  '~': 'Z', 'ْ': 'X', '}': 'C', '{': 'V', 'آ': 'N', '’': 'M', '؟': '?', 'ّ': '~',
};

const LIGATURES: Array<[string, string]> = [['لا', 'b'], ['لإ', 'T'], ['لأ', 'G'], ['لآ', 'B']];

const AR_DIGITS = '٠١٢٣٤٥٦٧٨٩';

export function normaliseScannerInput(raw: string): string {
  const s = raw.replace(/[​-‏‪-‮﻿]/g, '').replace(/[٠-٩]/g, (d) => String(AR_DIGITS.indexOf(d)));
  // ASCII بس → اتكتب والكيبورد إنجليزي، مفيش حاجة تتصلّح
  // (الرموز زي [ ] / { } بتتحوّل لحروف بس لو النص فيه عربي — يعني الكيبورد كان عربي أكيد)
  if (/^[\x20-\x7E]*$/.test(s)) return s;

  let out = '';
  for (let i = 0; i < s.length; i++) {
    const pair = s.slice(i, i + 2);
    const lig = LIGATURES.find(([ar]) => ar === pair);
    if (lig) { out += lig[1]; i++; continue; }
    const ch = s[i];
    out += AR_SHIFT[ch] ?? AR_PLAIN[ch] ?? ch;
  }
  return out;
}
